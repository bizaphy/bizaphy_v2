// Vocabulario de un texto del Almacen, una lista por fila (o undefined)
export function vocabularioDe(titulo: string): Palabra[][] | undefined {
  return DATOS[titulo]?.map((fila) =>
    fila.map((entrada) => {
      const [palabra, lectura, significado] = entrada.split("|");
      return { palabra, lectura, significado };
    }),
  );
}
